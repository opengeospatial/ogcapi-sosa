#!/usr/bin/env python3
"""
Generate grouped spec-example building blocks from a classification plan
(classify_examples.py) and install the Turtle -> JSON-LD transform.

Layout written under _sources/spec-examples/:
  examples.yaml                    examples with no SOSA root ('other'), Turtle validation only
  transforms/ttl_to_sosa_json.py   the installed transform script
  <group>/bblock.json              child block  ogc.sosa.spec-examples.<group>
  <group>/schema.yaml              $ref to the target bblock (inherits its context + SHACL)
  <group>/examples.yaml            the group's examples (by URL ref into the spec)
  <group>/transforms.yaml          ttl-to-jsonld transform, output profile = target bblock
  <group>/description.md
  closures/<base>.ttl              (hand-written, optional) SHACL closure for one example: added
                                   as the snippet's shacl-closure; <stem>.ttl applies to every
                                   root of a multi-root example

Generated files are overwritten; group directories no longer in the plan are reported,
not deleted.

Usage:
  python sync_spec_example_blocks.py --plan plan.yaml [--repo .] [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import yaml

SKILL_DIR = Path(__file__).resolve().parents[1]
TRANSFORM_ASSET = SKILL_DIR / 'assets' / 'ttl_to_sosa_json.py'
TRANSFORM_FILE = 'transforms/ttl_to_sosa_json.py'
CLOSURES_DIR = 'closures'
GENERATED_NOTE = 'Generated by the spec-examples-jsonld skill (sync_spec_example_blocks.py); edit the plan, not this file.'

# extra typed-literal coercions for the transform's local context (none needed since
# sosa-ssn.jsonld coerces resultTime/startTime/endTime to xsd:dateTime)
COERCE: dict[str, str] = {}
# GeoJSON alias of sosa:hasMember in sosa-ssn.jsonld; properties schemas use 'hasMember'
SUPPRESS = ['features']

GROUP_TITLES = {
    'observation-collections': 'Observation Collections',
    'sample-collections': 'Sample Collections',
    'observations': 'Observations',
    'samplings': 'Samplings',
    'actuations': 'Actuations',
    'deployments': 'Deployments',
    'samples': 'Samples',
    'platforms': 'Platforms',
    'systems': 'Systems (Sensors, Actuators, Samplers)',
}


def stem(url: str) -> str:
    return url.rsplit('/', 1)[-1].rsplit('.', 1)[0]


def local_name(iri: str) -> str:
    return iri.rstrip('/#').replace('#', '/').rsplit('/', 1)[-1]


def lang(url: str) -> str:
    return 'ttl' if url.endswith('.ttl') else 'jsonld'


def closure_ref(closures: Path, rel: str, *names: str) -> str | None:
    """Snippet shacl-closure path (relative to the block) for the first existing closures/<name>.ttl."""
    for n in names:
        if (closures / f'{n}.ttl').is_file():
            return f'{rel}{CLOSURES_DIR}/{n}.ttl'
    return None


def example_entries(entry: dict, siblings: dict[str, dict], closures: Path, rel: str) -> list[dict]:
    """examples.yaml entries for one classified example (one per root if several).

    rel is the path from the block directory to _sources/spec-examples/ ('' or '../')."""
    url, name = entry['url'], stem(entry['url'])
    snippets = [{'language': lang(url), 'ref': url}]
    if (sib := siblings.get(name)) is not None:
        snippets.append({'language': lang(sib['url']), 'ref': sib['url']})
    content = None
    if entry.get('chapters'):
        where = 'included in' if entry.get('in_document') == 'included' else 'referenced from'
        content = (f"Example {where} the SOSA/SSN specification section(s): "
                   + ', '.join(f"[{c}](https://w3c.github.io/sdw-sosa-ssn/ssn/)" for c in entry['chapters'])
                   + f". Source: [{url.rsplit('/', 1)[-1]}]({url})")
    roots = entry.get('roots') or []
    out = []
    for i, root in enumerate(roots or [None]):
        e = {'title': f"Example {url.rsplit('/', 1)[-1]}"}
        if len(roots) > 1:
            e['title'] += f" (root {local_name(root)})"
        if content:
            e['content'] = content
        base = name if url.endswith('.ttl') else f"{name}-{url.rsplit('.', 1)[-1]}"
        e['base-output-filename'] = base if i == 0 else f"{base}--{local_name(root)}"
        if len(roots) > 1:
            e['x-root'] = root
        e['snippets'] = [dict(sn) for sn in snippets]
        if closure := closure_ref(closures, rel, e['base-output-filename'], base):
            # validates the Turtle example and (postprocessor passes snippet closures on) the
            # transform output; the transform itself does not merge it into its output
            e['snippets'][0]['shacl-closure'] = [closure]
        out.append(e)
    return out


def bblock_json(parent: dict, group: str, target: str) -> dict:
    title = GROUP_TITLES.get(group, group)
    return {
        'name': f"SOSA specification examples: {title}",
        'abstract': (f"Examples from the SOSA/SSN specification whose root resource is a {title.lower()}"
                     f" resource. Each Turtle example is validated against the SHACL rules of `{target}`, "
                     f"and converted to JSON-LD by the `ttl-to-jsonld` transform, whose output is validated "
                     f"against the `{target}` building block (JSON Schema, JSON-LD context and SHACL)."),
        **{k: parent[k] for k in ('status', 'dateTimeAddition', 'itemClass', 'register', 'version',
                                  'dateOfLastChange', 'sources', 'maturity', 'scope', 'tags', 'group')
           if k in parent},
        'highlighted': False,
    }


def write(path: Path, text: str, dry: bool, written: list):
    written.append(path)
    if dry:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8', newline='\n')


class _NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def dump_yaml(data) -> str:
    return yaml.dump(data, Dumper=_NoAliasDumper, sort_keys=False, allow_unicode=True, width=120)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--plan', required=True)
    ap.add_argument('--repo', default='.')
    ap.add_argument('--dry-run', action='store_true')
    args = ap.parse_args()

    repo = Path(args.repo).resolve()
    root = repo / '_sources' / 'spec-examples'
    plan = yaml.safe_load(Path(args.plan).read_text(encoding='utf-8'))
    parent_meta = json.loads((root / 'bblock.json').read_text(encoding='utf-8'))
    parent_examples = yaml.safe_load((root / 'examples.yaml').read_text(encoding='utf-8')) or {}
    prefixes = parent_examples.get('prefixes') or {}

    examples = plan['examples']
    # JSON-LD originals stay separate examples (in 'other': they are RDF documents, not
    # schema-shaped JSON) with their own output name, so their reports don't overwrite the
    # Turtle example of the same name.
    siblings: dict[str, dict] = {}

    by_group: dict[str, list[dict]] = {}
    for e in examples:
        by_group.setdefault(e['group'], []).append(e)

    written: list[Path] = []
    used_closures: set[str] = set()
    groups = plan['groups']
    order = list(groups)
    for group, entries in by_group.items():
        rel = '' if group == 'other' else '../'
        yaml_examples = [x for e in entries for x in example_entries(e, siblings, root / CLOSURES_DIR, rel)]
        used_closures.update(c.rsplit('/', 1)[-1] for x in yaml_examples
                             for c in x['snippets'][0].get('shacl-closure', []))
        if group == 'other':
            write(root / 'examples.yaml', dump_yaml({'prefixes': prefixes, 'examples': yaml_examples}),
                  args.dry_run, written)
            continue
        target = groups[group]['target']
        container = [c for g in order[:order.index(group) + 1] for c in groups[g]['rootClasses']]
        d = root / group
        write(d / 'bblock.json', json.dumps(bblock_json(parent_meta, group, target), indent=2) + '\n',
              args.dry_run, written)
        write(d / 'schema.yaml', dump_yaml({
            '$schema': 'https://json-schema.org/draft/2020-12/schema',
            'description': f"SOSA specification examples conforming to {target}",
            '$ref': f'bblocks://{target}',
        }), args.dry_run, written)
        write(d / 'examples.yaml', dump_yaml({'prefixes': prefixes, 'examples': yaml_examples}),
              args.dry_run, written)
        write(d / 'transforms.yaml', dump_yaml({'transforms': [{
            'id': 'ttl-to-jsonld',
            'description': (f"Frames the root resource ({', '.join(c.rsplit('/', 1)[-1] for c in groups[group]['rootClasses'])}) of a SOSA Turtle "
                            f"example and compacts it with the `{target}` JSON-LD context. The output is "
                            f"validated against `{target}`."),
            'type': 'python',
            'ref': f'../{TRANSFORM_FILE}',
            'inputs': {'mediaTypes': ['text/turtle']},
            'outputs': {'mediaTypes': [{'mimeType': 'application/json', 'defaultExtension': 'json'}],
                        'profiles': [f'bblocks://{target}']},
            'metadata': {'rootClasses': groups[group]['rootClasses'], 'containerClasses': container,
                         **({'coerce': COERCE} if COERCE else {}), 'suppressTerms': SUPPRESS},
        }]}), args.dry_run, written)
        write(d / 'description.md', (
            f"## SOSA specification examples: {GROUP_TITLES.get(group, group)}\n\n"
            f"Examples from the [SOSA/SSN specification](https://w3c.github.io/sdw-sosa-ssn/ssn/) whose "
            f"root resource is validated against `{target}`.\n\n"
            "Each Turtle example is:\n\n"
            f"1. validated as RDF against the SHACL shapes inherited from `{target}`;\n"
            "2. converted by the `ttl-to-jsonld` transform: the root resource is framed and compacted "
            f"with the `{target}` JSON-LD context;\n"
            f"3. the transform output is validated against `{target}` (output profile validation): JSON "
            "Schema, JSON-LD uplift with the target context, and SHACL.\n\n"
            f"<!-- {GENERATED_NOTE} -->\n"), args.dry_run, written)

    if 'other' not in by_group:
        write(root / 'examples.yaml', dump_yaml({'prefixes': prefixes, 'examples': []}), args.dry_run, written)

    # install the transform script
    written.append(root / TRANSFORM_FILE)
    if not args.dry_run:
        (root / 'transforms').mkdir(exist_ok=True)
        shutil.copyfile(TRANSFORM_ASSET, root / TRANSFORM_FILE)

    for p in written:
        print(('would write ' if args.dry_run else 'wrote ') + str(p.relative_to(repo)).replace('\\', '/'))
    stale = [d.name for d in root.iterdir()
             if d.is_dir() and (d / 'bblock.json').exists() and d.name not in by_group]
    for s in stale:
        print(f"NOTE: group block '{s}' is not in the plan any more - review and delete it manually")
    for c in sorted((root / CLOSURES_DIR).glob('*.ttl')) if (root / CLOSURES_DIR).is_dir() else []:
        print(('using closure ' if c.name in used_closures else 'WARNING: closure matches no example: ')
              + str(c.relative_to(repo)).replace('\\', '/'))
    print(f"\n{sum(len(v) for v in by_group.values())} examples in {len(by_group)} groups: "
          + ', '.join(f"{g}={len(v)}" for g, v in by_group.items()))
    return 0


if __name__ == '__main__':
    sys.exit(main())
